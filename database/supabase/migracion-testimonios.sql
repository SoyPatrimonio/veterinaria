-- ---------------------------------------------------------------------
--  1. La tabla
--
--  El comentario que deja un cliente desde la página pública. Sale
--  publicado en cuanto pasa el filtro de palabras del servidor
--  (backend/src/utils/moderacion.js); nadie lo aprueba antes.
--
--  `publicado` es la forma de bajar uno de la página sin borrarlo:
--    UPDATE comunidad.testimonios SET publicado = 0 WHERE id = ?;
-- ---------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS comunidad.testimonios (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id INTEGER NULL,
  nombre     VARCHAR(80) NOT NULL,
  mensaje    VARCHAR(600) NOT NULL,
  publicado  SMALLINT NOT NULL DEFAULT 1,
  ip         VARCHAR(45) NULL,
  creado_en  TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP,
  CONSTRAINT chk_testimonios_publicado CHECK (publicado IN (0,1)),
  CONSTRAINT fk_testimonios_usuario FOREIGN KEY (usuario_id)
    REFERENCES usuarios.usuarios(id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_testimonios_publicados
  ON comunidad.testimonios (publicado, creado_en DESC);


-- ---------------------------------------------------------------------
--  2. Seguridad a nivel de base
--
--  En schema.sql esto lo hace un bucle sobre todas las tablas al final
--  del archivo, que aquí no corre. Sin ello, la tabla quedaría legible y
--  escribible a través de la API REST de Supabase con la clave anon, que
--  es pública: cualquiera podría insertar comentarios saltándose el
--  filtro de palabras y el freno anti-robots de la API de Express.
-- ---------------------------------------------------------------------

ALTER TABLE comunidad.testimonios ENABLE ROW LEVEL SECURITY;

DO $huellitas$
DECLARE
  r text;
BEGIN
  FOREACH r IN ARRAY ARRAY['anon','authenticated'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = r) THEN
      EXECUTE format('REVOKE ALL ON comunidad.testimonios FROM %I', r);
    END IF;
  END LOOP;
END
$huellitas$;


-- ---------------------------------------------------------------------
--  3. Comprobación
--
--  Debe devolver la tabla con RLS activado y 0 comentarios.
-- ---------------------------------------------------------------------

SELECT c.relname                                   AS tabla,
       c.relrowsecurity                            AS rls_activo,
       (SELECT COUNT(*) FROM comunidad.testimonios) AS comentarios
  FROM pg_class c
  JOIN pg_namespace n ON n.oid = c.relnamespace
 WHERE n.nspname = 'comunidad' AND c.relname = 'testimonios';
