-- ---------------------------------------------------------------------
--  1. Segundo factor (TOTP)
-- ---------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS seguridad.mfa (
  usuario_id      INTEGER PRIMARY KEY,
  secreto         VARCHAR(255) NOT NULL,
  activo          SMALLINT NOT NULL DEFAULT 0,
  ultimo_contador BIGINT NULL,
  creado_en       TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP,
  confirmado_en   TIMESTAMP(0) NULL,
  CONSTRAINT chk_mfa_activo CHECK (activo IN (0,1)),
  CONSTRAINT fk_mfa_usuario FOREIGN KEY (usuario_id)
    REFERENCES usuarios.usuarios(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS seguridad.mfa_codigos (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id  INTEGER NOT NULL,
  codigo_hash CHAR(64) NOT NULL,
  usado_en    TIMESTAMP(0) NULL,
  creado_en   TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP,
  CONSTRAINT uq_mfa_codigos UNIQUE (codigo_hash),
  CONSTRAINT fk_mfa_codigos_usuario FOREIGN KEY (usuario_id)
    REFERENCES usuarios.usuarios(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_mfa_codigos_usuario
  ON seguridad.mfa_codigos (usuario_id, usado_en);

-- El secreto TOTP pasa a guardarse cifrado (AES-256-GCM), y el valor cifrado
-- lleva dentro el nonce y la etiqueta, así que ya no cabe en VARCHAR(64).
-- Las filas que existan siguen en claro y se leen igual: se vuelven a guardar
-- cifradas la próxima vez que esa cuenta reconfigure su segundo factor.
ALTER TABLE seguridad.mfa
  ALTER COLUMN secreto TYPE VARCHAR(255);

CREATE TABLE IF NOT EXISTS seguridad.mfa_desafios (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id INTEGER NOT NULL,
  token_hash CHAR(64) NOT NULL,
  intentos   SMALLINT NOT NULL DEFAULT 0,
  ip         VARCHAR(45) NULL,
  agente     VARCHAR(255) NULL,
  creado_en  TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP,
  expira_en  TIMESTAMP(0) NOT NULL,
  usado_en   TIMESTAMP(0) NULL,
  CONSTRAINT uq_mfa_desafios UNIQUE (token_hash),
  CONSTRAINT fk_mfa_desafios_usuario FOREIGN KEY (usuario_id)
    REFERENCES usuarios.usuarios(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_mfa_desafios_usuario
  ON seguridad.mfa_desafios (usuario_id, usado_en);


