UPDATE seguridad.sesiones
   SET cerrada_en = LOCALTIMESTAMP, motivo_cierre = 'migracion_seguridad'
 WHERE cerrada_en IS NULL;


-- ---------------------------------------------------------------------
--  3. Comprobación
--
--  Debe devolver 7 cuentas marcadas, 0 sesiones abiertas y 3 tablas mfa.
-- ---------------------------------------------------------------------

SELECT
  (SELECT COUNT(*) FROM usuarios.usuarios WHERE debe_cambiar_password = 1) AS cuentas_marcadas,
  (SELECT COUNT(*) FROM seguridad.sesiones WHERE cerrada_en IS NULL)       AS sesiones_abiertas,
  (SELECT COUNT(*) FROM information_schema.tables
    WHERE table_schema = 'seguridad' AND table_name LIKE 'mfa%')           AS tablas_mfa;


